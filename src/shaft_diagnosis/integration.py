"""Causal structure routing and composition-conditioned attribute outputs.

Arrays use the structure order N, U, M, I, UM, UI, MI, UMI. Each row of
window evidence is 0.03 s apart within a continuous acquisition record.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import numpy as np

from . import _routing as routing
from . import _temporal as temporal

STRUCTURES = ("N", "U", "M", "I", "UM", "UI", "MI", "UMI")
HORIZON_WINDOWS = 281


def load_presence_models(repository_root):
    """Load the frozen three-component physical-presence calibration."""
    root = Path(repository_root)
    config = json.loads((root / "configs" / "integration.json").read_text(encoding="utf-8"))
    path = root / config["presence_model"]
    if hashlib.sha256(path.read_bytes()).hexdigest() != config["presence_model_sha256"]:
        raise ValueError("Presence-model checksum mismatch")
    models = {}
    with np.load(path, allow_pickle=False) as arrays:
        for branch in ("u", "m", "r"):
            models[branch] = {
                name: np.asarray(arrays[branch + "_" + name], dtype=np.float64)
                for name in ("center", "scale", "coefficient")
            }
            for name in ("oof_center", "oof_scale"):
                models[branch][name] = float(arrays[branch + "_" + name].reshape(-1)[0])
    return models, config


def context_indices(segment_id, rank, endpoints, stride=1):
    """Select a trailing 281-window history without crossing records."""
    segment = np.asarray(segment_id, dtype=np.int64)
    rank = np.asarray(rank, dtype=np.int64)
    endpoints = np.asarray(endpoints, dtype=np.int64)
    if segment.ndim != 1 or rank.shape != segment.shape or endpoints.ndim != 1:
        raise ValueError("Record IDs, ranks and endpoints must be one-dimensional")
    if len(np.unique(endpoints)) != len(endpoints):
        raise ValueError("Endpoints must be unique")
    if not isinstance(stride, (int, np.integer)) or stride <= 0:
        raise ValueError("History stride must be a positive integer")
    offsets = np.arange(HORIZON_WINDOWS - 1, -1, -stride, dtype=np.int64)
    ids = endpoints[:, None] - offsets[None, :]
    if ids.size and (np.min(ids) < 0 or np.max(ids) >= len(segment)):
        raise ValueError("Incomplete observation history")
    if not np.all(segment[ids] == segment[endpoints, None]):
        raise ValueError("Observation history crosses a record")
    if not np.all(rank[endpoints, None] - rank[ids] == offsets[None, :]):
        raise ValueError("Window ranks are not contiguous")
    return ids


def route_structure(window_probability, physical_features, segment_id, rank, endpoints, models, config):
    """Refine the two strongest temporal candidates using physical presence.

    Physical features have 15 columns and are generated by
    ``_routing.physics_feature_matrix`` on 10-channel, 6000-sample windows.
    """
    ids = context_indices(segment_id, rank, endpoints, stride=10)
    pooled = np.median(np.asarray(physical_features, dtype=np.float32)[ids], axis=1)
    if not np.isfinite(pooled).all():
        raise ValueError("Non-finite physical evidence")
    scores = routing.causal_temporal_scores(window_probability, segment_id, rank, endpoints, "mean_log")
    presence = routing.apply_presence_validators(models, pooled)
    result = routing.apply_safe_switch(scores, presence, config["presence_weight"],
                                       config["temporal_scale"], config["safe_switch_margin"])
    return {**result, "mean_log_score": scores, "standardized_presence": presence}


def aggregate_m_context(position_context, degree_context, quality_context):
    """Winsorized spatial probabilities and quality-weighted Huber severity.

    Inputs have shapes (batch, 281, 3), (batch, 281, 2), and (batch, 281).
    Quality is the frozen synchronous-degree acceptance flag, not confidence.
    """
    position_context = np.asarray(position_context)
    degree_context = np.asarray(degree_context)
    quality_context = np.asarray(quality_context)
    n = len(position_context)
    if position_context.shape != (n, HORIZON_WINDOWS, 3) or degree_context.shape != (n, HORIZON_WINDOWS, 2):
        raise ValueError("M histories must have shapes (N,281,3) and (N,281,2)")
    if quality_context.shape != (n, HORIZON_WINDOWS) or not np.isin(quality_context, (0, 1)).all():
        raise ValueError("M quality must have Boolean shape (N,281)")
    if any(not np.isfinite(v).all() or np.any(v < 0) for v in (position_context, degree_context)):
        raise ValueError("M probabilities must be finite and nonnegative")
    probability = temporal.normalize_probability(position_context)
    logp = np.log(np.clip(probability, temporal.EPS, 1.0))
    centered = logp - np.mean(logp, axis=2, keepdims=True)
    lower = np.quantile(centered, temporal.WINSOR_FRACTION, axis=1)
    upper = np.quantile(centered, 1.0 - temporal.WINSOR_FRACTION, axis=1)
    winsorized = np.minimum(np.maximum(centered, lower[:, None, :]), upper[:, None, :])
    position = temporal.softmax(np.mean(winsorized, axis=1))
    degree = temporal.normalize_probability(degree_context)
    log_odds = np.log(np.clip(degree[:, :, 1], temporal.EPS, 1.0)) - np.log(
        np.clip(degree[:, :, 0], temporal.EPS, 1.0))
    aligned = np.asarray(np.asarray(quality_context, dtype=np.uint8), dtype=np.float64)
    if aligned.shape != log_odds.shape:
        raise ValueError("Degree-quality context shape mismatch")
    weight = temporal.QUALITY_LOW_WEIGHT + (1.0 - temporal.QUALITY_LOW_WEIGHT) * aligned
    degree = temporal.degree_from_log_odds(temporal.huber_location(log_odds, weight))
    return (temporal.normalize_probability(position).astype(np.float32),
            temporal.normalize_probability(degree).astype(np.float32))


def aggregate_u(window_probability, segment_id):
    """Average the already-selected U readout within each trailing history."""
    endpoints, probability = temporal.rolling_group_mean(window_probability, segment_id, HORIZON_WINDOWS)
    probability = np.maximum(np.asarray(probability, dtype=np.float64), 0.0)
    probability /= np.maximum(np.sum(probability, axis=1, keepdims=True), 1.0e-12)
    return endpoints, probability.astype(np.float32)


def assemble_diagnosis(structure_index, u_prediction, m_position, m_degree, i_prediction,
                       u_ready, m_ready, i_ready):
    """Report only attributes admitted by the final structure; -1 is absent/unavailable."""
    route = np.asarray(structure_index, dtype=np.int64)
    if route.ndim != 1 or np.any((route < 0) | (route >= len(STRUCTURES))):
        raise ValueError("Invalid structure indices")
    bits = routing.STRUCTURE_BITS[route]
    output = {name: np.full(len(route), -1, dtype=np.int8)
              for name in ("u_prediction", "m_position_prediction", "m_degree_prediction",
                           "m_joint_prediction", "i_prediction")}
    for name, values, present in (
        ("u_prediction", u_prediction, (bits[:, 0] == 1) & np.asarray(u_ready, dtype=bool)),
        ("m_position_prediction", m_position, (bits[:, 1] == 1) & np.asarray(m_ready, dtype=bool)),
        ("m_degree_prediction", m_degree, (bits[:, 1] == 1) & np.asarray(m_ready, dtype=bool)),
        ("i_prediction", i_prediction, (bits[:, 2] == 1) & np.asarray(i_ready, dtype=bool)),
    ):
        values = np.asarray(values, dtype=np.int8)
        if values.shape != route.shape:
            raise ValueError("Attribute predictions must align with structure rows")
        output[name][present] = values[present]
    active_m = (bits[:, 1] == 1) & np.asarray(m_ready, dtype=bool)
    output["m_joint_prediction"][active_m] = (
        2 * output["m_position_prediction"][active_m] + output["m_degree_prediction"][active_m])
    output["structure_index"] = route.astype(np.int8)
    output["structure_label"] = np.asarray(STRUCTURES)[route]
    output["u_ready"] = np.asarray(u_ready, dtype=bool)
    output["m_ready"] = np.asarray(m_ready, dtype=bool)
    output["i_ready"] = np.asarray(i_ready, dtype=bool)
    return output
